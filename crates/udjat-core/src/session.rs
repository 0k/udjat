//! Sessions, messages and token usage.

use chrono::{DateTime, Utc};
use serde::Serialize;
use std::ops::Add;

use crate::HarnessKind;

/// `(llm_generation_s, tool_latency_s_before)` for a single assistant
/// message.  `None` for either field means "no signal" (see
/// [`crate::Harness::message_part_latencies`] for the contract).
pub type MessageLatencyPair = (Option<f64>, Option<f64>);

/// Map from `Message.timestamp` to its per-message latency pair.
pub type MessagePartLatencies = std::collections::HashMap<DateTime<Utc>, MessageLatencyPair>;

/// Harness-agnostic session metadata.
///
/// Fields common to every harness are present; harness-specific extras
/// (like `parent_id` for sub-agent sessions) use `Option`.
#[derive(Debug, Clone, Serialize)]
pub struct Session {
    pub session_id: String,
    /// Serialized as `provider`: consumers' JSON predates udjat.
    #[serde(rename = "provider")]
    pub harness: HarnessKind,
    pub started_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
    pub project_dir: String,
    pub title: String,
    /// Parent session ID (present for sub-agent sessions).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub parent_id: Option<String>,
}

/// Token usage for a single message exchange.
///
/// All fields represent token counts. Fields not applicable to a given
/// harness default to zero (e.g., `reasoning` is zero for Claude Code,
/// `cache_creation` is zero for OpenCode).
#[derive(Debug, Clone, Default, Serialize)]
pub struct TokenUsage {
    /// Input tokens (prompt tokens sent to the model).
    pub input: u64,
    /// Output tokens (completion tokens generated by the model).
    pub output: u64,
    /// Tokens read from cache.
    pub cache_read: u64,
    /// Tokens written to cache (OpenCode `cache.write`).
    pub cache_write: u64,
    /// Cache creation input tokens (Claude Code `cache_creation_input_tokens`).
    pub cache_creation: u64,
    /// Reasoning/thinking tokens (OpenCode-specific).
    pub reasoning: u64,
}

impl TokenUsage {
    /// Total tokens across all categories.
    pub fn total(&self) -> u64 {
        self.input
            + self.output
            + self.cache_read
            + self.cache_write
            + self.cache_creation
            + self.reasoning
    }

    /// Whether all fields are zero (no token data).
    pub fn is_empty(&self) -> bool {
        self.total() == 0
    }
}

impl Add for TokenUsage {
    type Output = Self;

    fn add(self, rhs: Self) -> Self {
        TokenUsage {
            input: self.input + rhs.input,
            output: self.output + rhs.output,
            cache_read: self.cache_read + rhs.cache_read,
            cache_write: self.cache_write + rhs.cache_write,
            cache_creation: self.cache_creation + rhs.cache_creation,
            reasoning: self.reasoning + rhs.reasoning,
        }
    }
}

impl std::iter::Sum for TokenUsage {
    fn sum<I: Iterator<Item = Self>>(iter: I) -> Self {
        iter.fold(TokenUsage::default(), |acc, x| acc + x)
    }
}

/// A single message exchange (user turn or assistant response) with its
/// token consumption when available.
#[derive(Debug, Clone, Serialize)]
pub struct Message {
    /// Unique message identifier.
    pub message_id: String,
    /// Session this message belongs to.
    pub session_id: String,
    /// Harness that produced this message.  Serialized as `provider`.
    #[serde(rename = "provider")]
    pub harness: HarnessKind,
    /// Role: "user" or "assistant".
    pub role: String,
    /// Model used for this message (if available).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub model: Option<String>,
    /// LLM provider id as reported by the harness — e.g.
    /// `"anthropic"`, `"openai-codex"`.  Not always present:
    /// Claude Code does not record this and it must be inferred
    /// downstream when needed.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub provider_id: Option<String>,
    /// Harness agent name (OpenCode `agent`, Pi sub-agent label).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub agent: Option<String>,
    /// Harness mode (OpenCode `mode`).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub mode: Option<String>,
    /// When this message was created.
    pub timestamp: DateTime<Utc>,
    /// Token usage (None for user messages, Some for assistant responses).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tokens: Option<TokenUsage>,
}

/// Model attribution for a session: which LLM wrote its latest
/// assistant activity.
///
/// * `model_id` is required.  Missing model metadata is a hard error,
///   never a silent fallback (see [`crate::Harness::resolve_attribution`]).
/// * `llm_provider` is optional; when it has to be inferred (Claude
///   Code does not record one), `llm_provider_inferred` is `true`.
/// * `access_surface` is the harness the human used (e.g.
///   `"OpenCode"`, `"Pi"`, `"ClaudeCode"`).
/// * `agent`, `mode`, `variant` are diagnostic-only.
#[derive(Debug, Clone, Serialize)]
pub struct ModelAttribution {
    pub harness: HarnessKind,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub llm_provider: Option<String>,
    pub llm_provider_inferred: bool,
    pub model_id: String,
    pub access_surface: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub agent: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub mode: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub variant: Option<String>,
}

/// Map an `llm_provider` id (as reported by a harness, or inferred from
/// a model id family) to the vendor brand name used as `AGENT_NAME` in
/// the kernel `Assisted-by: AGENT_NAME:MODEL_VERSION` trailer
/// (<https://www.kernel.org/doc/html/latest/process/coding-assistants.html>).
///
/// The harness readers refuse attribution whose provider has no brand,
/// so the table lives with the model.  Unknown provider ids return
/// `None`: callers must error or degrade explicitly, never substitute
/// the raw id.
pub fn brand_for_llm_provider(llm_provider: &str) -> Option<&'static str> {
    match llm_provider {
        "anthropic" => Some("Claude"),
        "openai" | "openai-codex" => Some("GPT"),
        "google" | "gemini" => Some("Gemini"),
        "xai" | "grok" => Some("Grok"),
        "meta" | "llama" => Some("Llama"),
        "mistral" => Some("Mistral"),
        "deepseek" => Some("DeepSeek"),
        _ => None,
    }
}

/// Best-effort inference of the LLM provider id from a model id, used
/// when the harness does not record an explicit provider field
/// (Claude Code is the canonical case).
///
/// Returns `Some(provider_id)` only when the model id maps unambiguously
/// to a known family.  Unknown families return `None` so the caller can
/// fail loudly instead of inventing attribution.
pub fn infer_llm_provider_from_model(model_id: &str) -> Option<&'static str> {
    let lower = model_id.to_ascii_lowercase();
    if lower.starts_with("claude-") {
        return Some("anthropic");
    }
    if lower.starts_with("gpt-") || lower.starts_with("o1-") || lower.starts_with("o3-") {
        return Some("openai");
    }
    if lower.starts_with("gemini-") {
        return Some("google");
    }
    if lower.starts_with("grok-") {
        return Some("xai");
    }
    if lower.starts_with("llama-") || lower.starts_with("llama3") || lower.starts_with("llama4") {
        return Some("meta");
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    fn usage(n: u64) -> TokenUsage {
        TokenUsage {
            input: n,
            output: 2 * n,
            cache_read: 3 * n,
            cache_write: 4 * n,
            cache_creation: 5 * n,
            reasoning: 6 * n,
        }
    }

    #[test]
    fn token_usage_total_and_empty() {
        assert_eq!(usage(1).total(), 21);
        assert!(TokenUsage::default().is_empty());
        assert!(!usage(1).is_empty());
    }

    #[test]
    fn token_usage_adds_and_sums_field_by_field() {
        let sum = usage(10) + usage(1);
        assert_eq!(
            (sum.input, sum.output, sum.cache_read, sum.cache_write),
            (11, 22, 33, 44)
        );
        assert_eq!((sum.cache_creation, sum.reasoning), (55, 66));
        let total: TokenUsage = [usage(1), usage(2), usage(3)].into_iter().sum();
        assert_eq!(total.total(), usage(6).total());
    }

    #[test]
    fn infers_llm_provider_from_model_family() {
        assert_eq!(
            infer_llm_provider_from_model("claude-sonnet-4-5"),
            Some("anthropic")
        );
        assert_eq!(
            infer_llm_provider_from_model("Claude-Opus-4-7"),
            Some("anthropic")
        );
        assert_eq!(infer_llm_provider_from_model("gpt-5.5"), Some("openai"));
        assert_eq!(infer_llm_provider_from_model("o1-preview"), Some("openai"));
        assert_eq!(
            infer_llm_provider_from_model("gemini-2.0-pro"),
            Some("google")
        );
        assert_eq!(infer_llm_provider_from_model("unknown-model"), None);
        assert_eq!(infer_llm_provider_from_model(""), None);
    }

    #[test]
    fn brands_known_llm_providers_only() {
        assert_eq!(brand_for_llm_provider("anthropic"), Some("Claude"));
        assert_eq!(brand_for_llm_provider("openai"), Some("GPT"));
        assert_eq!(brand_for_llm_provider("openai-codex"), Some("GPT"));
        assert_eq!(brand_for_llm_provider("google"), Some("Gemini"));
        assert_eq!(brand_for_llm_provider("gemini"), Some("Gemini"));
        assert_eq!(brand_for_llm_provider("nonsense-provider"), None);
        assert_eq!(brand_for_llm_provider(""), None);
    }

    #[test]
    fn session_and_message_serialize_the_harness_as_provider() {
        let session = Session {
            session_id: "ses_x".into(),
            harness: HarnessKind::OpenCode,
            started_at: DateTime::UNIX_EPOCH,
            updated_at: DateTime::UNIX_EPOCH,
            project_dir: "/p".into(),
            title: "t".into(),
            parent_id: None,
        };
        let json = serde_json::to_value(&session).unwrap();
        assert_eq!(json["provider"], "open_code");
        assert!(json.get("harness").is_none());
    }

    #[test]
    fn model_attribution_json_shape_is_stable() {
        let attr = ModelAttribution {
            harness: HarnessKind::OpenCode,
            llm_provider: Some("anthropic".to_string()),
            llm_provider_inferred: false,
            model_id: "claude-sonnet-4-5".to_string(),
            access_surface: "OpenCode".to_string(),
            agent: Some("build".to_string()),
            mode: Some("build".to_string()),
            variant: None,
        };
        let actual = serde_json::to_value(&attr).unwrap();
        let keys: Vec<&str> = actual
            .as_object()
            .unwrap()
            .keys()
            .map(|k| k.as_str())
            .collect();
        let mut keys = keys;
        keys.sort();
        assert_eq!(
            keys,
            [
                "access_surface",
                "agent",
                "harness",
                "llm_provider",
                "llm_provider_inferred",
                "mode",
                "model_id"
            ]
        );
        assert_eq!(actual["harness"], "open_code");
    }
}
